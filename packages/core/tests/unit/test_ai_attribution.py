import re
import sys

import pytest

from agent_hub.core import ai_attribution
from agent_hub.core.ai_attribution import carries_ai_attribution

# The hub guard's pattern (generator's guard.py.tmpl), which carries_ai_attribution follows, linear.
GUARD = re.compile(
    r"co-authored-by:\s*[^\n]*(claude|anthropic|openai|copilot|\bai\b)"
    r"|generated with \[?claude|\U0001f916",
    re.IGNORECASE,
)

MARKS = [
    pytest.param("Co-Authored-By: Claude <noreply@anthropic.com>", id="claude-trailer"),
    pytest.param("co-authored-by: Someone <bot@openai.com>", id="vendor-later-on-line"),
    pytest.param("CO-AUTHORED-BY: GitHub Copilot", id="copilot"),
    pytest.param("Co-Authored-By: an AI helper", id="ai-word"),
    pytest.param("Co-Authored-By:Claude", id="no-space"),
    pytest.param("Co-Authored-By:\tClaude", id="tab"),
    pytest.param("Co-Authored-By:\nClaude <noreply@anthropic.com>", id="newline"),
    pytest.param("Co-Authored-By: \t\n \nClaude", id="mixed-blank-lines"),
    pytest.param("Generated with [Claude Code](https://claude.ai)", id="generated-link"),
    pytest.param("generated with claude", id="generated-plain"),
    pytest.param("Ship it \U0001f916", id="robot"),
]

KEPT = [
    pytest.param("The hub schema is regenerated with make hub-schema", id="regenerated-with"),
    pytest.param("Ids are generated with uuid.uuid7()", id="generated-with-tool"),
    pytest.param("Commits carry no Co-Authored-By: trailer", id="tag-without-ai"),
    pytest.param("Co-Authored-By: Someone <someone@example.com>", id="human-co-author"),
    pytest.param("Co-Authored-By : Claude", id="space-before-colon"),
    pytest.param("Co-Authored-By:\n\nfirst line\nClaude later", id="vendor-past-first-line"),
    pytest.param("Generated  with Claude", id="two-spaces"),
    pytest.param("Generated\twith Claude", id="tab-in-generated-with"),
    pytest.param("generated by Claude", id="generated-by"),
    pytest.param("Ask Claude to fetch; maintain the AI-free rule", id="names-without-tag"),
    pytest.param("Co-Authored-By: the brain team", id="ai-inside-word"),
    pytest.param("", id="empty"),
]


@pytest.mark.parametrize("text", MARKS)
def test_finds_attribution_when_text_carries_ai_mark(text: str) -> None:
    assert carries_ai_attribution(text)
    assert GUARD.search(text) is not None


@pytest.mark.parametrize("text", KEPT)
def test_finds_no_attribution_when_text_is_honest(text: str) -> None:
    assert not carries_ai_attribution(text)
    assert GUARD.search(text) is None


@pytest.mark.parametrize(
    "text",
    [
        pytest.param("Co-Authored-By: x Co-Authored-By: Claude", id="second-tag-same-line"),
        pytest.param("Co-Authored-By:\nx\nCo-Authored-By: openai", id="second-tag-later-line"),
        pytest.param("Co-Authored-By:  \nCo-Authored-By: ai", id="tag-on-the-skipped-line"),
    ],
)
def test_finds_attribution_when_a_later_tag_names_ai(text: str) -> None:
    assert carries_ai_attribution(text)
    assert GUARD.search(text) is not None


class _CountingPattern:
    """The co-author pattern, counting the characters its searches are given to scan."""

    def __init__(self, pattern: re.Pattern[str]) -> None:
        self._pattern = pattern
        self.scanned = 0

    def search(self, text: str, pos: int = 0, endpos: int = sys.maxsize) -> re.Match[str] | None:
        self.scanned += min(endpos, len(text)) - pos
        return self._pattern.search(text, pos, endpos)


def test_runs_in_linear_time_when_text_is_dense_with_tags(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    # Every tag's blanks end on the same line: searching it again per tag would be quadratic.
    text = "co-authored-by:" * 50 + " " * 1_000 + "x"
    counting = _CountingPattern(ai_attribution._AI_CO_AUTHOR)  # noqa: SLF001 - wrapped, not changed
    monkeypatch.setattr(ai_attribution, "_AI_CO_AUTHOR", counting)

    assert carries_ai_attribution(text) is False
    assert 0 < counting.scanned <= len(text)
